#!/usr/bin/env node
// Builds serenity-aac.standalone.html — the whole app as one file, with no
// network dependency at all, for opening straight from disk (file://) or
// emailing/USB-dropping onto a tablet for a quick test.
//
// The ordinary multi-file app (index.html + css/ + js/ + data/ + assets/) is
// still how the app is actually deployed (see README, GitHub Pages). This is
// a derived testing artifact, not the source of truth, so it is not
// committed — regenerate it with:
//
//   npm run build:standalone
//
// Needs esbuild (`npm install --no-save esbuild`) purely to bundle the ES
// modules into one script with correct scoping; nothing about the app itself
// depends on esbuild.

import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, basename, extname } from 'node:path';
import esbuild from 'esbuild';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(join(root, p), 'utf8');
const readBin = (p) => readFileSync(join(root, p));

const MIME = { '.woff2': 'font/woff2', '.svg': 'image/svg+xml', '.png': 'image/png' };
const dataUri = (path) => `data:${MIME[extname(path)]};base64,${readBin(path).toString('base64')}`;

/* ── 1. CSS: concatenated verbatim, fonts inlined as data: URIs ─────────── */

let css = ['theme.css', 'layout.css', 'components.css']
  .map((f) => read(`css/${f}`))
  .join('\n\n');

css = css.replace(
  /url\("\.\.\/assets\/fonts\/([^"]+)"\)/g,
  (_, file) => `url("${dataUri(`assets/fonts/${file}`)}")`
);
if (css.includes('../assets/fonts/')) {
  throw new Error('A font @font-face url was not inlined — check css/theme.css.');
}

/* ── 2. Icons: every hand-drawn SVG as a data: URI, keyed by name ───────── */

const iconFiles = readdirSync(join(root, 'assets/icons')).filter((f) => f.endsWith('.svg'));
const icons = {};
for (const file of iconFiles) icons[basename(file, '.svg')] = dataUri(`assets/icons/${file}`);
const iconsJson = JSON.stringify(icons);

/* ── 3. Vocabulary: embedded as a JSON script tag js/vocabulary.js reads ── */

const vocabJson = read('data/vocabulary.json').trim();
JSON.parse(vocabJson); // fail loudly here, not silently inside the browser

/* ── 4. App code: bundle the ES modules into one scope with esbuild ─────── */

const bundled = await esbuild.build({
  entryPoints: [join(root, 'js/main.js')],
  bundle: true,
  format: 'iife',
  target: 'es2020',
  write: false,
  legalComments: 'none',
});
const appScript = bundled.outputFiles[0].text;

/* ── 5. Assemble the page ────────────────────────────────────────────────
   Same shell as index.html, minus the bits that make no sense without a
   server or a separate origin (manifest, service worker, external <link>s):
   a lone file has nothing to install a manifest against, and main.js already
   no-ops service-worker registration under location.protocol === 'file:'. */

const shell = read('index.html');
const bodyMatch = shell.match(/<body>([\s\S]*)<\/body>/);
if (!bodyMatch) throw new Error('Could not find <body> in index.html — did its structure change?');

let body = bodyMatch[1]
  .replace(/<script type="module" src="js\/main\.js"><\/script>\s*/, '');

const favicon = dataUri('assets/icons/core.svg');

const html = `<!doctype html>
<html lang="en" data-theme="crayon" data-size="m" data-labels="on">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no, viewport-fit=cover">
<title>Serenity — My Talking App (standalone test build)</title>
<meta name="description" content="A picture-and-word communication board. Single-file build for local testing — open this file directly, no server needed.">
<meta name="theme-color" content="#fffaf0">
<link rel="icon" href="${favicon}" type="image/svg+xml">
<style>
${css}
</style>
</head>
<body>
${body}
<script id="vocab-data" type="application/json">
${vocabJson}
</script>
<script>
// Read by js/render.js's iconSrc() in place of assets/icons/<name>.svg —
// see the comment there. Generated by tools/build-standalone.mjs.
window.SERENITY_ICONS = ${iconsJson};
</script>
<script type="module">
${appScript}
</script>
</body>
</html>
`;

const outPath = join(root, 'serenity-aac.standalone.html');
writeFileSync(outPath, html);

const kb = (n) => `${(n / 1024).toFixed(0)}KB`;
console.log(`Wrote serenity-aac.standalone.html (${kb(html.length)})`);
console.log(`  css ${kb(css.length)} · vocab ${kb(vocabJson.length)} · icons ${kb(iconsJson.length)} (${iconFiles.length} files) · app js ${kb(appScript.length)}`);
console.log('This file has no network dependency: open it directly (file://), no server needed.');
