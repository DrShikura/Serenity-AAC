#!/usr/bin/env node
// Builds data/vocabulary.json from the authored sources in tools/vocab/.
// Run: node tools/build-vocabulary.mjs

import { writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

import { compile, board } from './dsl.mjs';
import { core, home } from './vocab/core.mjs';
import { boards as foodBoards } from './vocab/food.mjs';
import { boards as playBoards } from './vocab/play.mjs';
import { boards as bodyBoards } from './vocab/body.mjs';
import { boards as worldBoards } from './vocab/world.mjs';
import { boards as thingBoards } from './vocab/things.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

// The keyboard board is generated by the renderer rather than authored button
// by button, so it declares no grid of its own.
const keyboard = {
  ...board('keyboard', 'Letters', 'svg:keyboard', 'social', 0, 0, []),
  special: 'keyboard',
};

const boards = [
  home,
  ...foodBoards,
  ...playBoards,
  ...bodyBoards,
  ...worldBoards,
  ...thingBoards,
  keyboard,
];

const vocab = compile([core, ...boards], { corePage: 'core' });

// Grammar endings. Hidden behind a settings toggle by default; the bar grows
// with her rather than cluttering the board now.
vocab.grammarBar = [
  { id: 'gram.plural', label: '-s', hint: 'more than one', op: 'plural' },
  { id: 'gram.ing', label: '-ing', hint: 'doing it now', op: 'ing' },
  { id: 'gram.past', label: '-ed', hint: 'already happened', op: 'past' },
  { id: 'gram.will', label: 'will', hint: 'going to happen', op: 'will' },
  { id: 'gram.possessive', label: "'s", hint: 'belongs to', op: 'possessive' },
  { id: 'gram.negate', label: "don't", hint: 'make it a no', op: 'negate' },
  { id: 'gram.a', label: 'a', hint: 'a thing', op: 'article_a' },
  { id: 'gram.the', label: 'the', hint: 'that thing', op: 'article_the' },
];

// Swatch names used by buttons, resolved to CSS custom properties at render time.
vocab.colors = [
  'core', 'people', 'verb', 'describe', 'noun',
  'social', 'question', 'negation', 'urgent',
];

mkdirSync(join(root, 'data'), { recursive: true });
writeFileSync(join(root, 'data', 'vocabulary.json'), JSON.stringify(vocab, null, 2) + '\n');

const total = vocab.boards.reduce(
  (n, b) => n + b.buttons.filter(Boolean).length, 0
);
console.log(`Wrote data/vocabulary.json — ${vocab.boards.length} boards, ${total} buttons.`);
